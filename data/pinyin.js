// 菜名 + 食材合并索引
export const PINYIN_INDEX = { ...DISH_PINYIN, ...INGREDIENT_PINYIN };

const HANZI_RE = /[一-龥]/g;

// 取中文词的首字母缩写；未收录返回空串
export function getPinyinInitials(text) {
  if (!text) return "";
  const direct = PINYIN_INDEX[text];
  if (direct) return direct;
  return "";
}

// 是否为纯中文输入（拼音首字母检索的适用场景）
export function isHanziQuery(keyword) {
  const chars = String(keyword || "").trim();
  return chars.length > 0 && HANZI_RE.test(chars);
}
